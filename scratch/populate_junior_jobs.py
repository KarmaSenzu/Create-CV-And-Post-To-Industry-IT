from ruamel.yaml import YAML

yaml = YAML(typ="safe")
with open("master/master.yaml") as f:
    master = yaml.load(f)

# Master skills lookup set
master_skills = set()
for g in master["skills"]:
    for item in g["items"]:
        master_skills.add(item.lower())

